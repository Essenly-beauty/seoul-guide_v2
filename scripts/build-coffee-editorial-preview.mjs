import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const sourceDir = path.join(root, "data", "sources", "coffeelog-korea");
const manifest = JSON.parse(await readFile(path.join(sourceDir, "editorial-series-2026-10-15.json"), "utf8"));
const labels = JSON.parse(await readFile(path.join(sourceDir, "research-labels-2026-09-26.json"), "utf8"));
const candidates = JSON.parse(await readFile(path.join(sourceDir, "seoul-cafe-candidates-2026-09-22.json"), "utf8"));
const checklists = await Promise.all([
  "publication-checklist-priority-1-3.json",
  "publication-checklist-priority-4-6.json",
  "publication-checklist-priority-7-8.json",
].map(async (filename) => JSON.parse(await readFile(path.join(sourceDir, filename), "utf8"))));

const researchById = new Map(labels.records.map((record) => [record.canonical_place_id, record]));
const candidateByExternalId = new Map(candidates.records.map((record) => [record.external_id, record]));
const draftPathBySeriesId = new Map(checklists.flatMap((checklist) => checklist.series).map((item) => [item.series_id, item.draft_path]));

function cleanParagraph(value) {
  return value.replace(/\n+/g, " ").replace(/\s+/g, " ").trim();
}

async function readDraft(seriesId, expectedPlaces) {
  const relativePath = draftPathBySeriesId.get(seriesId);
  if (!relativePath) throw new Error(`Missing draft path: ${seriesId}`);
  const markdown = await readFile(path.join(sourceDir, relativePath), "utf8");
  const withoutFrontmatter = markdown.replace(/^---\n[\s\S]*?\n---\n/, "");
  const publicationMatch = withoutFrontmatter.match(/^> 발행 메모:\s*(.+)$/m);
  const publicationNote = publicationMatch ? cleanParagraph(publicationMatch[1]) : "";
  const mainCopy = withoutFrontmatter.replace(/^> 발행 메모:[\s\S]*$/m, "").trim();
  const sections = mainCopy.split(/^## /m);
  const introduction = cleanParagraph(sections.shift().replace(/^# .+\n+/, ""));
  const placeBodies = sections.map((section) => cleanParagraph(section.replace(/^.+\n+/, "")));
  if (placeBodies.length !== expectedPlaces) {
    throw new Error(`${seriesId}: expected ${expectedPlaces} draft sections, found ${placeBodies.length}`);
  }
  return { introduction, placeBodies, publicationNote };
}

const series = await Promise.all(manifest.series.map(async (item) => {
  const draft = await readDraft(item.id, item.places.length);
  return {
    id: item.id,
    slug: item.slug,
    priority: item.priority,
    titleKo: item.title_ko,
    titleEn: item.title_en,
    dekKo: item.dek_ko,
    introduction: draft.introduction,
    publicationNote: draft.publicationNote,
    occasionTags: item.occasion_tags,
    places: item.places.map((place, index) => {
    const research = researchById.get(place.canonical_place_id);
    if (!research) throw new Error(`Missing research: ${place.canonical_place_id}`);
    const candidate = candidateByExternalId.get(research.member_external_ids[0]);
    if (!candidate) throw new Error(`Missing candidate: ${research.member_external_ids[0]}`);
    return {
      canonicalPlaceId: place.canonical_place_id,
      order: place.order,
      name: candidate.source_name.replace(/\s*📍\s*$/, ""),
      district: candidate.district_ko,
      editorialNote: place.editorial_note,
      body: draft.placeBodies[index],
      attributes: research.verified_attributes.slice(0, 5),
      cautions: research.cautions.slice(0, 2),
    };
    }),
  };
}));

const output = `/* Generated by scripts/build-coffee-editorial-preview.mjs. Do not edit directly. */\n\nexport const COFFEE_EDITORIAL_SERIES = ${JSON.stringify(series, null, 2)} as const;\n\nexport type CoffeeEditorialSeries = (typeof COFFEE_EDITORIAL_SERIES)[number];\n`;
await writeFile(path.join(root, "lib", "generated", "coffee-editorial.ts"), output, "utf8");
console.log(`Generated ${series.length} coffee editorial series.`);
