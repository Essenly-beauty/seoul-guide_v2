#!/usr/bin/env node
// Owner-supplied place photos → lib/generated/place-photos.ts
// (owner decision 2026-08-22: real photos come from us first; a Google
// Places import stays an option and would write the same generated map.)
//
//   1. Drop files into  public/places/<place-id>/
//      e.g. public/places/glow-skin-clinic/1.jpg, 2.jpg, 3.jpg
//   2. node scripts/build-place-photos.mjs
//
// Files are served same-origin, so the CSP needs no change. Order follows
// the filename, so name them 1,2,3 to control what the two-up rail shows
// first. A folder whose name is not a real place id is reported loudly
// rather than silently ignored — a typo'd id is the likeliest mistake.

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PHOTO_DIR = join(ROOT, "public", "places");
const OUT = join(ROOT, "lib", "generated", "place-photos.ts");
const ALLOWED = /\.(jpe?g|png|webp|avif)$/i;
/** A rail tile is ~175px wide at 3x — anything past this is wasted bytes. */
const WARN_BYTES = 600_000;

// Place ids are read out of the source files rather than imported — this is a
// plain node script and lib/data.ts is TypeScript.
const knownIds = new Set();
for (const file of [
  join(ROOT, "lib", "data.ts"),
  join(ROOT, "lib", "generated", "creatrip-places.ts"),
  join(ROOT, "lib", "generated", "oliveyoung-places.ts"),
  join(ROOT, "lib", "generated", "ados-places.ts"),
]) {
  if (!existsSync(file)) continue;
  for (const m of readFileSync(file, "utf8").matchAll(/\bid:\s*"([^"]+)"/g)) knownIds.add(m[1]);
}

if (!existsSync(PHOTO_DIR)) {
  console.log(`no ${PHOTO_DIR} yet — create it and drop photos into per-place folders`);
}

const photos = {};
const unknown = [];
let count = 0;
let heavy = 0;

for (const entry of existsSync(PHOTO_DIR) ? readdirSync(PHOTO_DIR) : []) {
  const dir = join(PHOTO_DIR, entry);
  if (!statSync(dir).isDirectory()) continue;
  if (!knownIds.has(entry)) {
    unknown.push(entry);
    continue;
  }
  const files = readdirSync(dir)
    .filter((f) => ALLOWED.test(f))
    .sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
  if (files.length === 0) continue;
  for (const f of files) {
    if (statSync(join(dir, f)).size > WARN_BYTES) {
      heavy++;
      console.log(`  heavy: places/${entry}/${f} — resize under ${Math.round(WARN_BYTES / 1000)}KB`);
    }
  }
  photos[entry] = files.map((f) => `/places/${entry}/${f}`);
  count += files.length;
}

const header = `// GENERATED by scripts/build-place-photos.mjs — do not edit by hand.
// Owner-supplied photos, served same-origin from public/places/<place-id>/.
// Places absent from this map have no verified photo and must render the
// honest empty state — never a placeholder tile dressed up as a gallery.

export const PLACE_PHOTOS: Record<string, string[]> = `;

writeFileSync(
  OUT,
  header + JSON.stringify(photos, null, 2).replace(/"([a-zA-Z][\w-]*)":/g, '"$1":') + ";\n",
);

console.log(`\n${count} photos across ${Object.keys(photos).length} places → ${OUT}`);
if (heavy > 0) console.log(`${heavy} file(s) over ${Math.round(WARN_BYTES / 1000)}KB — the rail only needs ~525px wide`);
if (unknown.length > 0) {
  console.log(`\n⚠ folders that are not place ids (check the spelling): ${unknown.join(", ")}`);
  process.exitCode = 1;
}
